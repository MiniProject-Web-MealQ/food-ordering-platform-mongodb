const MINUTE = 60_000;
const DAY = 24 * 60 * MINUTE;

function pastOrder({ id, restaurantId, daysAgo, items, paymentMethod = "promptpay", review = null }) {
  const placedAt = Date.now() - daysAgo * DAY;
  const subtotal = items.reduce((sum, item) => sum + item.unitPrice * item.qty, 0);
  return {
    id,
    restaurantId,
    items,
    subtotal,
    serviceFee: SERVICE_FEE,
    discount: 0,
    couponCode: null,
    total: subtotal + SERVICE_FEE,
    paymentMethod,
    queueNumber: 20 + (Number(id.slice(2)) % 40),
    nowServing: 0,
    etaMinutes: [8, 12],
    pickupCode: String(1000 + (Number(id.slice(2)) % 9000)),
    statusTimes: {
      PLACED: placedAt,
      PAID: placedAt,
      QUEUED: placedAt + MINUTE,
      PREPARING: placedAt + 6 * MINUTE,
      READY: placedAt + 12 * MINUTE,
      PICKED_UP: placedAt + 15 * MINUTE,
    },
    review,
  };
}

function line(menuId, name, unitPrice, optionLabels = [], qty = 1, note = "") {
  return { key: `${menuId}|seed`, menuId, name, unitPrice, qty, optionLabels, note };
}

